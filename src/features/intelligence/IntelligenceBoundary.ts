import { PersonalContext } from '../context/PersonalContextService';
import { DailyVersion } from '../life-version/models';
import { PersonalPatterns } from '../patterns/PersonalPatternService';

/**
 * Comprehensive State representing the boundary between existing V1 architecture
 * and the upcoming intelligence breakthrough.
 * 
 * This aggregates all necessary dimensions without duplicating state:
 * - Stable: preferences, obstacles, taste
 * - Observed: patterns, memories
 * - Current: today's state, logged meals, wellness, time
 * - Decisions: existing Daily Version
 */
export interface BreakthroughIntelligenceState {
  // Stable & Explicit Preferences
  preferences: PersonalContext['preferences'];
  
  // Observed Personal Patterns
  patterns: PersonalPatterns;
  
  // Current Day State
  currentDayState: PersonalContext['current'];
  
  // The deterministic Daily Version currently generated by V1
  dailyVersion: DailyVersion;
  
  // High-level User Actions & Memories
  memories: PersonalContext['memories'];
  
  // Temporal Context
  timestamp: string;
}

/**
 * Extension Point for the future Intelligence Engine.
 * Must enforce the "Why" and maintain the calm, non-intrusive identity.
 */
export interface IntelligenceEngineBoundary {
  /**
   * Future intelligence will evaluate the comprehensive state here.
   * For now, this is a clean pass-through boundary.
   */
  evaluateState(state: BreakthroughIntelligenceState): void;

  /**
   * Enforces the "Why": Any future personalization MUST be able to explain
   * its decisions using real evidence from the state, not invented logic.
   */
  explainDecision(actionId: string, state: BreakthroughIntelligenceState): string | null;
}

/**
 * Default implementation of the extension point.
 * Freezes the current V1 logic while providing a hook for the upcoming architecture.
 */
export class CoreIntelligenceOrchestrator implements IntelligenceEngineBoundary {
  
  evaluateState(state: BreakthroughIntelligenceState): void {
    // The breakthrough feature will be injected here.
    // Currently, it acts as a stable observation boundary.
  }

  explainDecision(actionId: string, state: BreakthroughIntelligenceState): string | null {
    // Falls back to deterministic reasons generated by V1 engine
    const recommendation = state.dailyVersion.priorities.find(p => p.id === actionId);
    if (recommendation && recommendation.reason) {
      return recommendation.reason;
    }
    
    // If no evidence is found, the system must remain quiet.
    return null;
  }
}

/**
 * Helper to construct the BreakthroughIntelligenceState from existing V1 context.
 */
export function buildIntelligenceState(
  context: PersonalContext, 
  dailyVersion: DailyVersion
): BreakthroughIntelligenceState {
  return {
    preferences: context.preferences,
    patterns: context.patterns.inferred,
    currentDayState: context.current,
    memories: context.memories,
    dailyVersion,
    timestamp: new Date().toISOString()
  };
}
